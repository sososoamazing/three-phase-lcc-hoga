function status = lcc3v2Accept(hoga,referenceFine,referenceCoarse,refChange,orderChange,p)
%lcc3v2Accept Require both references, physical guards, H and event convergence.
arguments
    hoga (1,1) struct
    referenceFine (1,1) struct
    referenceCoarse (1,1) struct
    refChange (1,1) struct
    orderChange (1,1) struct
    p (1,1) struct
end
status = 'NOT CONVERGED';
if ~hoga.converged_algebraic || ~referenceFine.converged_periodic || ...
        ~referenceCoarse.converged_periodic
    return
end
if ~hoga.physical_guard_pass || ~referenceFine.physical_guard_pass || ...
        ~referenceCoarse.physical_guard_pass
    status = 'FAIL';
    return
end
if isempty(fieldnames(orderChange)) || isempty(fieldnames(refChange))
    return
end
referenceConverged = refChange.Irect_mean_A_relative < 1e-4 && ...
    refChange.iLine_peak_A_relative < 1e-3 && refChange.jSec_peak_A_relative < 1e-3 && ...
    refChange.event_topology_match && refChange.event_time_max_T < 1e-5;
orderConverged = orderChange.Irect_mean_A_relative < p.order_integral_rel && ...
    orderChange.iLine_rms_A_relative < p.order_integral_rel && ...
    orderChange.jSec_rms_A_relative < p.order_integral_rel && ...
    orderChange.iLine_peak_A_relative < p.order_peak_rel && ...
    orderChange.jSec_peak_A_relative < p.order_peak_rel && ...
    orderChange.vCs_peak_V_relative < p.order_peak_rel && ...
    orderChange.vDelta_peak_V_relative < p.order_peak_rel && ...
    orderChange.event_topology_match && orderChange.event_time_max_T < p.event_time_tol_T;
if ~isfield(orderChange,'previous_change') || isempty(fieldnames(orderChange.previous_change))
    orderConverged = false;
else
    before = orderChange.previous_change;
    orderConverged = orderConverged && before.Irect_mean_A_relative < p.order_integral_rel && ...
        before.iLine_rms_A_relative < p.order_integral_rel && before.jSec_rms_A_relative < p.order_integral_rel && ...
        before.iLine_peak_A_relative < p.order_peak_rel && before.jSec_peak_A_relative < p.order_peak_rel && ...
        before.vCs_peak_V_relative < p.order_peak_rel && before.vDelta_peak_V_relative < p.order_peak_rel && ...
        before.event_topology_match && before.event_time_max_T < p.event_time_tol_T;
end
agreement = lcc3v2Compare(hoga,referenceFine);
referenceAgrees = agreement.Irect_mean_A_relative < p.order_integral_rel && ...
    agreement.iLine_rms_A_relative < p.order_integral_rel && ...
    agreement.jSec_rms_A_relative < p.order_integral_rel && ...
    agreement.iLine_peak_A_relative < p.order_peak_rel && ...
    agreement.jSec_peak_A_relative < p.order_peak_rel && ...
    agreement.vCs_peak_V_relative < p.order_peak_rel && ...
    agreement.vDelta_peak_V_relative < p.order_peak_rel && ...
    agreement.event_topology_match && agreement.event_time_max_T < p.event_time_tol_T && ...
    agreement.i_A_wave_relative_L2 < 0.01 && agreement.vCs_V_wave_relative_L2 < 0.01 && ...
    agreement.vDelta_V_wave_relative_L2 < 0.01 && agreement.jSecondary_A_wave_relative_L2 < 0.02;
if referenceConverged && orderConverged && referenceAgrees
    status = 'PASS';
end
end
